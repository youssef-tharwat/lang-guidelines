"""Split the three Rust upstream sources into addressable units.

Unit ids are stable keys the manifest refers to:

- ``M-PANIC-IS-STOP`` — a Microsoft Pragmatic Rust Guideline, by its own id;
- ``G:<anchor>`` — a Google Rust Style Guide section, by its page anchor;
- ``P:<path>`` — a rust-unofficial patterns page, by its path under ``/patterns/``;
- ``GOF:<slug>`` — a refactoring.guru Gang-of-Four page, by its URL slug.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING

from .errors import BuildError
from .guide import split_sections
from .markdown_text import HEADING_RE, clean_body, close_open_fence, heading, map_prose, scan, slugify
from .pages import drop_first_heading, first_heading, gang_of_four_unit, split_pages
from .units import Source, Unit

if TYPE_CHECKING:
    from pathlib import Path

MICROSOFT = Source(
    title="Microsoft Pragmatic Rust Guidelines",
    license="MIT",
    home="https://microsoft.github.io/rust-guidelines/",
)
GOOGLE = Source(
    title="Google Rust Style Guide",
    license="CC BY 3.0",
    home="https://google.github.io/styleguide/rustguide.html",
)
UNOFFICIAL = Source(
    title="Rust Design Patterns (rust-unofficial)",
    license="MPL-2.0",
    home="https://rust-unofficial.github.io/patterns/",
)
GANG_OF_FOUR = Source(
    title="Design Patterns in Rust (refactoring.guru)",
    license="CC BY-SA 4.0",
    home="https://refactoring.guru/design-patterns/rust",
)

MICROSOFT_FILE = "microsoft-pragmatic-rust-guidelines.md"
GOOGLE_FILE = "google-rust-style-guide.md"
PATTERNS_FILE = "rust-patterns.md"

GUIDELINE_HEADING_LEVEL = 2
MICROSOFT_ID_RE = re.compile(r"\{ #(?P<id>M-[A-Z0-9-]+) \}$", re.MULTILINE)
MICROSOFT_HEADING_RE = re.compile(r"^(?P<title>.+?) \((?P<id>M-[A-Z0-9-]+)\) \{ #M-[A-Z0-9-]+ \}$")
MICROSOFT_DROP_LINE_RE = re.compile(r"^\s*(<why>.*</why>|<version>.*</version>|</?div[^>]*>)\s*$")
MICROSOFT_TAG_RE = re.compile(r"</?(alert|tip|footnotes)>|<br/>")
SUPERSCRIPT_RE = re.compile(r"<sup>(?P<mark>[^<]+)</sup>")
TOML_FENCE_RE = re.compile(r"```toml\n(?P<body>.*?)\n```", re.DOTALL)
GOOGLE_ROOT = "# Google Rust Style Guide"


def load_units(sources_dir: Path) -> list[Unit]:
    """Parse every Rust upstream source in ``sources_dir``."""
    return [
        *parse_microsoft((sources_dir / MICROSOFT_FILE).read_text(encoding="utf-8")),
        *parse_google((sources_dir / GOOGLE_FILE).read_text(encoding="utf-8")),
        *parse_patterns((sources_dir / PATTERNS_FILE).read_text(encoding="utf-8")),
    ]


class MissingLintTablesError(BuildError):
    """M-STATIC-VERIFICATION no longer carries the TOML lint tables ``lints.toml`` is built from."""

    def __init__(self) -> None:
        """Explain which upstream section to inspect."""
        super().__init__("M-STATIC-VERIFICATION has no ```toml lint tables; update extra_outputs for the new source")


def extra_outputs(sources_dir: Path) -> dict[str, str]:
    """Return ``lints.toml``, assembled from the lint tables in M-STATIC-VERIFICATION."""
    raw = _microsoft_sections((sources_dir / MICROSOFT_FILE).read_text(encoding="utf-8"))
    tables = TOML_FENCE_RE.findall(raw.get("M-STATIC-VERIFICATION", ("", ""))[1])
    if not tables:
        raise MissingLintTablesError
    header = (
        "# Lint tables from M-STATIC-VERIFICATION (Microsoft Pragmatic Rust Guidelines, MIT).\n"
        "# Generated by build/compile.py; merge into the workspace Cargo.toml [lints] tables.\n"
    )
    return {"lints.toml": header + "\n" + "\n\n".join(tables) + "\n"}


def _microsoft_sections(text: str) -> dict[str, tuple[str, str]]:
    """Map each guideline id to ``(title, raw body)``.

    A guideline heading always starts a new section, even when the previous section left a
    code fence open (upstream has shipped one), so one malformed example can't swallow the
    guidelines after it. Within a section, the body stops at the next top-level heading or
    thematic break outside code, and a fence still open at the end is closed.
    """
    sections: dict[str, tuple[str, str]] = {}
    current: tuple[str, str] | None = None
    lines: list[str] = []

    def flush() -> None:
        if current:
            sections[current[0]] = (current[1], close_open_fence(_guideline_body("\n".join(lines))))

    for raw in text.split("\n"):
        found = HEADING_RE.match(raw)
        match = (
            MICROSOFT_HEADING_RE.match(found.group("title"))
            if found and len(found.group("hashes")) == GUIDELINE_HEADING_LEVEL
            else None
        )
        if match:
            flush()
            current = (match.group("id"), match.group("title"))
            lines = []
            continue
        lines.append(raw)
    flush()
    return sections


def _guideline_body(section: str) -> str:
    """Cut a guideline's section at the first top-level heading or thematic break outside code."""
    kept: list[str] = []
    for line in scan(section):
        found = heading(line)
        is_thematic_break = not line.in_fence and line.text.strip() == "---"
        if (found is not None and found[0] < GUIDELINE_HEADING_LEVEL) or is_thematic_break:
            break
        kept.append(line.text)
    return "\n".join(kept)


def _clean_microsoft_line(line: str) -> str:
    if MICROSOFT_DROP_LINE_RE.match(line):
        return ""
    return SUPERSCRIPT_RE.sub(r"^\g<mark>", MICROSOFT_TAG_RE.sub("", line))


class MissingGuidelinesError(BuildError):
    """The parser produced fewer guidelines than the source declares."""

    def __init__(self, missing: set[str]) -> None:
        """Name every guideline the source declares but the parser lost."""
        super().__init__(f"Microsoft source declares guidelines the parser lost: {', '.join(sorted(missing))}")


def parse_microsoft(text: str) -> list[Unit]:
    """One unit per ``M-*`` guideline; fail if any declared guideline was not parsed."""
    sections = _microsoft_sections(text)
    missing = {match.group("id") for match in MICROSOFT_ID_RE.finditer(text)} - sections.keys()
    if missing:
        raise MissingGuidelinesError(missing)
    return [
        Unit(
            unit_id=unit_id,
            title=title,
            url=MICROSOFT.home,
            body=clean_body(map_prose(body, _clean_microsoft_line)),
            source=MICROSOFT,
        )
        for unit_id, (title, body) in sections.items()
    ]


def parse_google(text: str) -> list[Unit]:
    """One unit per section that carries rules: every h3, and any h2 with text before its first h3."""
    _, _, guide = text.partition(GOOGLE_ROOT)
    units: list[Unit] = []
    for section in split_sections(guide, frozenset({2, 3})):
        anchor = slugify(section.title) if section.title else "intro"
        units.append(
            Unit(
                unit_id=f"G:{anchor}",
                title=section.title or "Introduction",
                url=GOOGLE.home if anchor == "intro" else f"{GOOGLE.home}#{anchor}",
                body=clean_body(section.body),
                source=GOOGLE,
            )
        )
    return units


def parse_patterns(text: str) -> list[Unit]:
    """One unit per upstream page: rust-unofficial pages by path, refactoring.guru pages by slug."""
    units: list[Unit] = []
    for page in split_pages(text):
        gang_of_four = gang_of_four_unit(page, GANG_OF_FOUR)
        if gang_of_four:
            units.append(gang_of_four)
            continue
        path = page.url.split("/patterns/", 1)[1].removesuffix(".html")
        units.append(
            Unit(
                unit_id=f"P:{path}",
                title=first_heading(page.text) or path,
                url=page.url,
                body=clean_body(drop_first_heading(page.text)),
                source=UNOFFICIAL,
            )
        )
    return units
